function scrollToDocsSection(anchorId) {
  const content = $("#docsContent");
  const el = content?.querySelector(`#${CSS.escape(anchorId)}`);
  if (el) {
    el.scrollIntoView({ behavior: "smooth", block: "start" });
    highlightDocsTocLink(anchorId);
  }
}

function highlightDocsTocLink(anchorId) {
  $$("#docsToc [data-docs-anchor]").forEach((btn) => {
    btn.classList.toggle("active", btn.dataset.docsAnchor === anchorId);
  });
}

function openDocsModal() {
  const modal = $("#docsModal");
  const content = $("#docsContent");
  if (!modal || !content) return;
  if (!content.dataset.rendered) {
    content.innerHTML = renderDocsMarkdown(DOCS_MANUAL_MD);
    renderDocsToc();
    content.dataset.rendered = "1";
    content.addEventListener("scroll", () => {
      const headings = content.querySelectorAll("h2[id]");
      let current = "";
      const top = content.scrollTop + 24;
      headings.forEach((h) => {
        if (h.offsetTop <= top) current = h.id;
      });
      if (current) highlightDocsTocLink(current);
    });
  }
  modal.classList.remove("hidden");
  document.body.style.overflow = "hidden";
}

function closeDocsModal() {
  const modal = $("#docsModal");
  if (!modal) return;
  modal.classList.add("hidden");
  document.body.style.overflow = "";
  $("#docsToc")?.classList.remove("open");
}

function bindDocs() {
  $("#docsBtn")?.addEventListener("click", openDocsModal);
  $$("[data-docs-close]").forEach((el) => {
    el.addEventListener("click", closeDocsModal);
  });
  $("#docsTocBtn")?.addEventListener("click", () => {
    $("#docsToc")?.classList.toggle("open");
  });
  document.addEventListener("keydown", (e) => {
    if (e.key === "Escape" && !$("#docsModal")?.classList.contains("hidden")) {
      closeDocsModal();
    }
  });
}

bindDocs();
